// Builds en/navod.html (served at /en/navod) from navod/index.html: the same install
// guide with an English <head> and no-JS fallback. The page picks its language from
// the path (/en/ = English), so the body stays identical.
//
// Why a second file: Google renders pages with an English browser, so the old
// "follow the browser language" logic got the Czech /navod indexed in English, and
// /navod?lang=en (canonical /navod) was indexed as a page of its own. Each language
// now has one URL with its own static <head> and a cs/en hreflang pair.
//
// Run after every change to navod/index.html:  node scripts/navod-en.mjs
// CI runs it with --check and fails when en/navod.html is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const src = readFileSync(new URL('navod/index.html', root), 'utf8');

const swaps = [
  ['<html lang="cs">', '<html lang="en">'],
  ['<title>reIS – Nainstaluj za dvě minuty</title>', '<title>reIS – Install it in two minutes</title>'],
  [
    '<meta name="description" content="Nainstaluj reIS rozšíření za dvě minuty. Vyber zařízení a prohlížeč — zbytek tě provedeme krok po kroku.">',
    '<meta name="description" content="Install reIS for MENDELU in two minutes. Pick your device and browser and follow the steps.">',
  ],
  ['<link rel="canonical" href="https://reisapp.cz/navod">', '<link rel="canonical" href="https://reisapp.cz/en/navod">'],
  ['<meta property="og:url" content="https://reisapp.cz/navod">', '<meta property="og:url" content="https://reisapp.cz/en/navod">'],
  ['<meta property="og:title" content="reIS – Nainstaluj za dvě minuty">', '<meta property="og:title" content="reIS – Install it in two minutes">'],
  [
    '<meta property="og:description" content="Nainstaluj reIS za dvě minuty. Vyber zařízení a prohlížeč — zbytek tě provedeme krok po kroku.">',
    '<meta property="og:description" content="Install reIS in two minutes. Pick your device and browser and follow the steps.">',
  ],
  ['<meta property="og:image" content="https://reisapp.cz/og.png">', '<meta property="og:image" content="https://reisapp.cz/og-en.png">'],
  ['<meta property="og:locale" content="cs_CZ">', '<meta property="og:locale" content="en_GB">'],
  ['>Nainstaluj reIS za dvě minuty</h1>', '>Install reIS in two minutes</h1>'],
  ['<p>reIS je přehlednější UIS MENDELU v telefonu i v prohlížeči.</p>', '<p>reIS makes the MENDELU information system (UIS) easy to use, on your phone and in your browser.</p>'],
  ['<p><a href="/navody">Návody</a> · <a href="/">reisapp.cz</a></p>', '<p><a href="/en/guides">Guides</a> · <a href="/en">reisapp.cz</a></p>'],
];

let out = src;
for (const [from, to] of swaps) {
  const n = out.split(from).length - 1;
  if (n !== 1) {
    console.error(`navod-en: expected exactly one "${from}" in navod/index.html, found ${n}. Update the swaps in scripts/navod-en.mjs.`);
    process.exit(1);
  }
  out = out.replace(from, to);
}
out = out.replace(
  '<!DOCTYPE html>\n',
  '<!DOCTYPE html>\n<!-- GENERATED by scripts/navod-en.mjs from navod/index.html. Do not edit; edit the Czech file and rerun. -->\n',
);

const target = new URL('en/navod.html', root);
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(target, 'utf8'); } catch {}
  if (cur !== out) {
    console.error('en/navod.html is out of date: run node scripts/navod-en.mjs and commit it.');
    process.exit(1);
  }
  console.log('en/navod.html is up to date.');
} else {
  writeFileSync(target, out);
  console.log('wrote en/navod.html');
}
